#!/usr/bin/env python3
"""Offline guardrails for the dated partial review, not a live-source verifier."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]
REVIEW = ROOT / 'review/146bcd33/index.html'

class TableAudit(HTMLParser):
    def __init__(self):
        super().__init__(); self.in_body = False; self.in_row = False; self.links = []; self.rows = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        assert not any(k.lower().startswith('on') for k in attrs)
        assert tag not in ('script', 'iframe', 'form')
        if tag == 'tbody': self.in_body = True
        if tag == 'tr' and self.in_body: self.in_row = True; self.links = []
        for key in ('href', 'src'):
            val = attrs.get(key)
            if not val: continue
            parsed = urlsplit(val)
            assert not parsed.scheme or (parsed.scheme == 'https' and parsed.hostname and not parsed.username and not parsed.password), val
            if not parsed.scheme and parsed.path:
                assert (REVIEW.parent / parsed.path).resolve().is_file(), val
            if self.in_row and key == 'href' and parsed.scheme == 'https': self.links.append(parsed.hostname)
    def handle_endtag(self, tag):
        if tag == 'tr' and self.in_row: self.rows.append(self.links); self.in_row = False
        if tag == 'tbody': self.in_body = False

def validate(text):
    assert 'NO HALLUCINATIONS' in text and 'partial' in text.lower()
    audit = TableAudit(); audit.feed(text)
    assert len(audit.rows) == 10, len(audit.rows)
    allowed = {'www.bluenile.com', 'www.allurez.com', 'www.kitco.com'}
    assert all(any(host in allowed for host in row) for row in audit.rows), 'A review row lacks an approved primary-source link'

text = REVIEW.read_text(); validate(text)
for mutated in (text.replace('NO HALLUCINATIONS', 'NO RULE'), text.replace('https://www.allurez.com/pages/return-policy', 'javascript:alert(1)'), text.replace('https://www.allurez.com/pages/return-policy', 'https://example.com/fake')):
    try: validate(mutated)
    except AssertionError: pass
    else: raise AssertionError('Planted defect was not detected')
for path in [ROOT / 'index.html', *sorted((ROOT / 'site').glob('*.html'))]:
    # The independently produced master audit is not generated by build_site.py.
    if path.name == 'master-audit.html': continue
    content = path.read_text()
    assert 'Historical snapshot — not current purchase information' in content, path
    assert 'review/146bcd33/index.html' in content, path
print('PASS: dated review source links, local links, historical warnings and 3 injected defects; no live truth verified')
